/// A [PixelGlyph] at [size] logical pixels (default 16: two pixels per dot).
class PixelIcon extends StatelessWidget {
  const PixelIcon(this.glyph, {super.key, this.size = 16, this.color});

  final PixelGlyph glyph;
  final double size;
  final Color? color;

  @override
  Widget build(BuildContext context) {
    return CustomPaint(
      size: Size.square(size),
      painter: _GlyphPainter(glyph, color ?? context.retro.ink),
    );
  }
}

class _GlyphPainter extends CustomPainter {
  _GlyphPainter(this.glyph, this.color);

  final PixelGlyph glyph;
  final Color color;

  @override
  void paint(Canvas canvas, Size size) {
    final dot = size.width / 8;
    final paint = Paint()
      ..color = color
      ..isAntiAlias = false;
    for (var y = 0; y < glyph.rows.length; y++) {
      final row = glyph.rows[y];
      for (var x = 0; x < row.length; x++) {
        if (row[x] == '#') {
          canvas.drawRect(Rect.fromLTWH(x * dot, y * dot, dot, dot), paint);
        }
      }
    }
  }

  @override
  bool shouldRepaint(_GlyphPainter old) =>
      old.glyph != glyph || old.color != color;
}
